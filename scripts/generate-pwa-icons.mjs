#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const iconsDir = path.join(root, 'public', 'icons');
const sourceSvg = path.join(iconsDir, 'source-icon.svg');

const svg = await readFile(sourceSvg);

/** Maskable icons need ~20% safe zone — scale logo down inside square. */
async function maskableSvg(size) {
  const inner = Math.round(size * 0.62);
  const offset = Math.round((size - inner) / 2);
  const wrapped = `
    <svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
      <rect width="${size}" height="${size}" fill="#131313"/>
      <svg x="${offset}" y="${offset}" width="${inner}" height="${inner}" viewBox="0 0 512 512">
        ${svg.toString().replace(/<\/?svg[^>]*>/g, '')}
      </svg>
    </svg>
  `;
  return Buffer.from(wrapped);
}

await mkdir(iconsDir, { recursive: true });

const sizes = [
  { name: 'icon-192.png', size: 192, maskable: false },
  { name: 'icon-512.png', size: 512, maskable: false },
  { name: 'icon-512-maskable.png', size: 512, maskable: true },
  { name: 'apple-touch-icon.png', size: 180, maskable: false },
];

for (const { name, size, maskable } of sizes) {
  const input = maskable ? await maskableSvg(size) : svg;
  const out = path.join(iconsDir, name);
  await sharp(input).resize(size, size).png().toFile(out);
  console.log(`Wrote ${out}`);
}

await writeFile(
  path.join(iconsDir, 'README.txt'),
  'Generated by npm run pwa:icons — edit source-icon.svg then regenerate.\n',
);

console.log('PWA icons ready.');
